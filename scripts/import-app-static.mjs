#!/usr/bin/env node
// Embed the Local API Server's static files — the OpenAPI document and the Swagger UI it is rendered
// with — from the app, where the Rust proxy compiles the same files in with `include_str!`.
//
// Embedded as string constants rather than read from disk because the compiled core binary has no
// resource directory of its own when it runs as a CLI, and the docs page must still work there.
// The replay fixtures (`test/fixtures/app/proxy-http/docs_*`) pin the served bytes by sha256, so a
// stale copy fails the contract test instead of drifting quietly.
//
//   node scripts/import-app-static.mjs [--app ../Atomic-Chat]
import { readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'

const ROOT = new URL('..', import.meta.url).pathname
const appArg = process.argv.indexOf('--app')
const APP = resolve(ROOT, appArg > -1 ? process.argv[appArg + 1] : '../Atomic-Chat')
const STATIC = join(APP, 'src-tauri/static')

const files = {
  OPENAPI_JSON: 'openapi.json',
  SWAGGER_UI_CSS: 'swagger-ui/swagger-ui.css',
  SWAGGER_UI_BUNDLE_JS: 'swagger-ui/swagger-ui-bundle.js',
}

let out =
  '// Generated by scripts/import-app-static.mjs from ../Atomic-Chat/src-tauri/static. Do not edit.\n' +
  '/* eslint-disable */\n'
for (const [name, file] of Object.entries(files)) {
  out += `export const ${name}: string = ${JSON.stringify(readFileSync(join(STATIC, file), 'utf8'))}\n`
}
const target = join(ROOT, 'src/server/public/static-assets.generated.ts')
writeFileSync(target, out)
console.log(`wrote ${target}`)

#!/usr/bin/env node
// The GenieX host's Worker as a string (change add-geniex-runtime, design D1): `worker.ts` and what
// it imports (`ffi-bun.ts`, the protocol) bundled by Bun into one script, written as a generated TS
// module that `host/engine.ts` imports and starts as a `blob:` Worker. A Worker named by a path does
// not start from inside a compiled Windows binary on the Bun that CI pins (1.3.10): the embedded
// `B:\~BUN\root\worker.js` is read from the real disk (ENOENT; oven-sh/bun#16869, #29124, fixed in
// 1.4.1), while a blob needs no path on any platform. Run before `tsc` (so the published `dist`
// carries it for `atc`) and before `bun build --compile`; the output is not committed.
//
//   node scripts/build-geniex-worker.mjs
import { spawnSync } from 'node:child_process'
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
const WORKER_ENTRY = join(ROOT, 'src/runtime/geniex/host/worker.ts')
export const WORKER_SOURCE_MODULE = join(ROOT, 'src/runtime/geniex/host/worker-source.generated.ts')

/** Bundles the Worker and writes the generated module; throws when Bun fails. */
export function buildGeniexWorkerSource() {
  const dir = mkdtempSync(join(tmpdir(), 'atomic-geniex-worker-'))
  try {
    const outfile = join(dir, 'worker.js')
    // No source map: a blob Worker has no file for one. Errors of the library cross the protocol as
    // messages anyway; a crash of the native code takes the whole host, map or not.
    const args = [
      'build',
      '--target=bun',
      '--minify-syntax',
      '--minify-whitespace',
      WORKER_ENTRY,
      '--outfile',
      outfile,
    ]
    const res = spawnSync('bun', args, { stdio: 'inherit', cwd: ROOT })
    if (res.status !== 0) throw new Error(`bun ${args.join(' ')} failed (${res.status ?? res.signal})`)
    const code = readFileSync(outfile, 'utf8')
    writeFileSync(
      WORKER_SOURCE_MODULE,
      [
        '// Generated by scripts/build-geniex-worker.mjs from src/runtime/geniex/host/worker.ts — not committed,',
        '// not edited by hand. The GenieX host starts this script as a blob: Worker (host/engine.ts).',
        `export const GENIEX_WORKER_SOURCE: string = ${JSON.stringify(code)}`,
        '',
      ].join('\n')
    )
  } finally {
    rmSync(dir, { recursive: true, force: true })
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  buildGeniexWorkerSource()
  console.log(`generated ${WORKER_SOURCE_MODULE}`)
}
